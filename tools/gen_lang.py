#!/usr/bin/env python3
"""Builds src/lang_table.inc from src/lang/<code>.txt.

Every file has one line per string of enum Str (c2s.h), in the same order; en.txt is the reference. In a line a newline
is written \\n and a backslash \\\\. The generator checks the line counts and that every language keeps the printf
placeholders (%s %d %lu ...) of the English string in the same order. Run from anywhere: python3 tools/gen_lang.py
"""
import os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
LANGS = [   # (file code, native name)
    ('en', 'English'), ('ru', 'Русский'), ('uk', 'Українська'), ('be', 'Беларуская'), ('de', 'Deutsch'),
    ('fr', 'Français'), ('es', 'Español'), ('it', 'Italiano'), ('pt', 'Português (Brasil)'), ('pl', 'Polski'),
    ('nl', 'Nederlands'), ('tr', 'Türkçe'), ('id', 'Bahasa Indonesia'), ('vi', 'Tiếng Việt'), ('zh', '中文(简体)'),
    ('ja', '日本語'), ('ko', '한국어'),
]
PLACE = re.compile(r'%(?:[-+ 0#]*)(?:\d+|\*)?(?:\.\d+)?(?:l|ll|h)?[sdiuxXc]')

def read(code):
    path = os.path.join(ROOT, 'lang', code + '.txt')
    with open(path, encoding='utf-8') as f:
        lines = f.read().split('\n')
    if lines and lines[-1] == '':
        lines.pop()
    out = []
    for l in lines:
        s = re.sub(r'\\(.)', lambda m: '\n' if m.group(1) == 'n' else m.group(1), l)
        out.append(s)
    return out

def wide(s):
    """C++ wide string literal; every non-ASCII char as \\xNNNN in its own literal piece (hex escapes are greedy)."""
    parts, cur = [], ''
    def flush():
        nonlocal cur
        if cur:
            parts.append('L"' + cur + '"'); cur = ''
    for ch in s:
        o = ord(ch)
        if ch == '\n': cur += '\\n'
        elif ch == '"': cur += '\\"'
        elif ch == '\\': cur += '\\\\'
        elif 32 <= o < 127: cur += ch
        else:
            flush()
            if o > 0xFFFF:
                o -= 0x10000
                parts.append('L"\\x%04x"' % (0xD800 + (o >> 10))); parts.append('L"\\x%04x"' % (0xDC00 + (o & 0x3FF)))
            else:
                parts.append('L"\\x%04x"' % o)
    flush()
    return ' '.join(parts) if parts else 'L""'

def main():
    en = read('en')
    n = len(en)
    bad = 0
    tables = []
    for code, _ in LANGS:
        t = read(code)
        if len(t) != n:
            print('%s.txt: %d lines, expected %d' % (code, len(t), n)); bad += 1; continue
        for i, (a, b) in enumerate(zip(en, t)):
            if not b.strip():
                print('%s.txt line %d is empty' % (code, i + 1)); bad += 1
            pa, pb = PLACE.findall(a.replace('%USERNAME%', '')), PLACE.findall(b.replace('%USERNAME%', ''))
            if pa != pb:
                print('%s.txt line %d: placeholders %s, English has %s' % (code, i + 1, pb, pa)); bad += 1
        tables.append(t)
    if bad:
        sys.exit(1)
    out = ['// Generated by tools/gen_lang.py from src/lang/*.txt - do not edit.\n',
           'static const int kLangCount = %d;\n' % len(LANGS),
           'static const wchar_t* const kLangNames[kLangCount] = {\n']
    out += ['    %s,\n' % wide(name) for _, name in LANGS]
    out.append('};\n')
    out.append('static const wchar_t* const kStrings[kLangCount][%d] = {\n' % n)
    for (code, _), t in zip(LANGS, tables):
        out.append('    { // %s\n' % code)
        out += ['        %s,\n' % wide(s) for s in t]
        out.append('    },\n')
    out.append('};\n')
    with open(os.path.join(ROOT, 'lang_table.inc'), 'w', encoding='utf-8') as f:
        f.write(''.join(out))
    print('lang_table.inc: %d languages, %d strings each' % (len(LANGS), n))

if __name__ == '__main__':
    main()
